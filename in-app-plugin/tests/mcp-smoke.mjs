import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const profile = path.join(root, '../tests/artifacts/in-app-mcp');
fs.mkdirSync(profile, { recursive: true });
const skinFixture=path.join(profile,'CodexDreamSkin','active-theme');fs.mkdirSync(skinFixture,{recursive:true});fs.writeFileSync(path.join(skinFixture,'theme.json'),JSON.stringify({id:'mcp-veil-fixture'}));
const client = new Client({ name: 'plugin-verification', version: '1.0.0' });
const runtime = process.argv.includes('--dist') ? path.join(root, 'dist') : root;
const manifest = JSON.parse(fs.readFileSync(path.join(runtime, '.mcp.json'), 'utf8')).mcpServers.launch_animation;
assert.ok(!JSON.stringify(manifest).includes('${'), 'Installed manifest must not contain unresolved runtime variables');
const transport = new StdioClientTransport({ command: process.execPath, args: [path.join(runtime,'server.cjs')], cwd: runtime, env: { ...process.env, CODEX_LAUNCHER_TEST_DATA: profile } });
try {
  await client.connect(transport);
  const capabilities = client.getServerCapabilities();
  assert.equal(capabilities.experimental['openai/settings'].readTool, 'animation_settings_read');
  const tools = (await client.listTools()).tools;
  assert.deepEqual(tools.find(tool => tool.name === 'open_animation_control')._meta['openai/ui'].entrypoints, [{ type: 'global' }, { type: 'thread' }]);
  const read = name => client.callTool({ name, arguments: {} });
  const configuration = await read('get_animation_configuration');
  assert.ok(configuration.structuredContent.settings.layout.iconSize > 0);
  const veil=(await read('get_skin_veil')).structuredContent;assert.equal(veil.available,true);
  const masked=await client.callTool({name:'set_skin_veil',arguments:{themeId:veil.themeId,opacity:20}});assert.equal(masked.structuredContent.opacity,20);
  const wrongVeil=await client.callTool({name:'set_skin_veil',arguments:{themeId:'stale',opacity:20}});assert.equal(wrongVeil.isError,true);
  const invalidVeil=await client.callTool({name:'set_skin_veil',arguments:{themeId:veil.themeId,opacity:101}});assert.equal(invalidVeil.isError,true);
  assert.deepEqual((await read('get_animation_configuration')).structuredContent.settings,configuration.structuredContent.settings,'Mask controls must preserve all animation settings');
  const speed=await client.callTool({name:'update_animation_configuration',arguments:{settings:{motion:{gatherSpeed:2}}}});
  assert.equal(speed.structuredContent.settings.motion.gatherSpeed,2);
  const invalidSpeed=await client.callTool({name:'update_animation_configuration',arguments:{settings:{motion:{gatherSpeed:0}}}});
  assert.equal(invalidSpeed.isError,true);
  const rotation=await client.callTool({name:'update_animation_configuration',arguments:{settings:{motion:{rotationSpeed:1.5}}}});
  assert.equal(rotation.structuredContent.settings.motion.rotationSpeed,1.5);
  assert.equal(rotation.structuredContent.settings.motion.gatherSpeed,2);
  const invalidRotation=await client.callTool({name:'update_animation_configuration',arguments:{settings:{motion:{rotationSpeed:0}}}});
  assert.equal(invalidRotation.isError,true);
  const saved = await client.callTool({ name: 'update_animation_configuration', arguments: { settings: { autoPlay: true, uiLanguage: 'en', colors:{openingStart:'#ff0099',brandIcon:'#55ccaa',name:'#ff8844'},text: { name: { font: 'Consolas', fontSize: 72, x: 65 } }, layout: { iconSize: 300 } } } });
  assert.equal(saved.structuredContent.settings.text.name.fontSize, 72);
  assert.equal(saved.structuredContent.settings.uiLanguage, 'en');
  assert.equal(saved.structuredContent.settings.colors.openingStart,'#ff0099');assert.equal(saved.structuredContent.settings.colors.brandIcon,'#55ccaa');
  const invalidColor=await client.callTool({name:'update_animation_configuration',arguments:{settings:{colors:{name:'url(secret)'}}}});assert.equal(invalidColor.isError,true);
  const native = await read('animation_settings_read');
  assert.equal(native.structuredContent.values.autoPlay, true);
  assert.ok(native.structuredContent.layout[0].items.some(item => item.tool === 'preview_animation'));
  await client.callTool({ name: 'animation_settings_update', arguments: { set: { autoPlay: false } } });
  const disabled = (await read('get_animation_configuration')).structuredContent.settings;
  assert.equal(disabled.autoPlay, false); assert.equal(disabled.text.name.fontSize, 72);
  assert.equal(disabled.motion.gatherSpeed,2);
  assert.equal(disabled.motion.rotationSpeed,1.5);
  const invalid = await client.callTool({ name: 'update_animation_configuration', arguments: { settings: { layout: { iconSize: 'bad' } } } });
  assert.equal(invalid.isError, true);
  const resource = await client.readResource({ uri: tools.find(tool => tool.name === 'open_animation_control')._meta.ui.resourceUri });
  assert.deepEqual(resource.contents[0]._meta.ui.csp.resourceDomains, ['blob:']);
  assert.deepEqual(resource.contents[0]._meta['openai/widgetCSP'].resource_domains, ['blob:']);
  const html = resource.contents[0].text;
  assert.ok(html.length < 4000000); assert.ok(!html.includes('<iframe')); assert.ok(!/(?:src|href)=["'](?:https?:|file:)/i.test(html));
  assert.equal(resource.contents[0].mimeType, 'text/html;profile=mcp-app');
  const original = fs.readFileSync(path.join(root, 'assets/gpt6-stars-full.mp4'));
  const hash = crypto.createHash('sha256');
  let offset = 0;
  while (offset < original.length) {
    const chunk = (await client.callTool({ name: 'read_animation_media', arguments: { offset, length: 524288 } })).structuredContent;
    assert.ok(chunk.next > offset); assert.equal(chunk.total, original.length);
    hash.update(Buffer.from(chunk.data, 'base64')); offset = chunk.next;
  }
  assert.equal(hash.digest('hex'), crypto.createHash('sha256').update(original).digest('hex'));
  console.log('PASS: real MCP handshake, sidebar metadata, native settings, persisted controls, invalid input rejection, complete video transport.');
} finally { await client.close(); }
